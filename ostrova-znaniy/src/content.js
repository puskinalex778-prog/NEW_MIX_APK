/* ---------- Мастерская умножения ---------- */
function mulLesson(k) {
  const pick = () => k || R(2, 9);
  const ex = () => { const a = pick(), b = R(2, 9); return [`${a} × ${b}`, a * b]; };
  const four = uniq(4, () => JSON.stringify(ex())).map(JSON.parse);
  const uniqRes = []; four.forEach(e => { if (!uniqRes.some(u => u[1] === e[1])) uniqRes.push(e); });
  const six = uniq(6, () => JSON.stringify(ex())).map(JSON.parse);
  const a = pick(), st = R(1, 5);
  const [e1, r1] = ex(), [e2, r2] = ex();
  return [
    T.choice('Умножение', e1 + ' = ?', r1, near(r1, 3, Math.max(4, a)), 'Умножение — это сложение одинаковых чисел.'),
    T.match('Найди ответ', uniqRes.map(e => [e[0], e[1]]), 'Вспомни таблицу умножения.'),
    T.order(`Продолжи счёт через ${a}`, [a * st, a * (st + 1), a * (st + 2), a * (st + 3)].map(String).sort((x, y) => x - y), `Каждое следующее число больше на ${a}.`),
    T.sort('Ответ меньше 30 или не меньше?', [['lt', 'Меньше 30', '🐣'], ['ge', '30 и больше', '🦖']], six.map(e => [e[0], e[1] < 30 ? 'lt' : 'ge']), 'Сначала реши пример, потом сравни с 30.'),
    T.choice('Умножение', e2 + ' = ?', r2, near(r2, 3, 6), 'Если трудно, посчитай по шагам.')
  ];
}

