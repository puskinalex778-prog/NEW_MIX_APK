/* ===== Задания. Типы: choice (выбор), sort (разложить по группам), order (порядок), match (пары) ===== */
const R = (a, b) => a + Math.floor(Math.random() * (b - a + 1));
const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const sample = (a, n) => shuffle(a).slice(0, n);
const uniq = (n, f) => { const s = new Set(); let g = 0; while (s.size < n && g++ < 500) s.add(f()); return [...s]; };

const T = {
  choice: (title, prompt, answer, wrong, hint, sub) => ({ type: 'choice', title, prompt, answer: String(answer), options: shuffle([String(answer), ...wrong.map(String)]), hint, sub: sub || 'Нажми на правильный ответ' }),
  sort: (title, groups, items, hint, sub) => ({ type: 'sort', title, groups, items: shuffle(items), hint, sub: sub || 'Перетащи пальцем каждую карточку в нужную группу' }),
  order: (title, items, hint, sub) => ({ type: 'order', title, items, hint, sub: sub || 'Перетащи карточки в окошки по порядку' }),
  match: (title, pairs, hint, sub) => ({ type: 'match', title, pairs, hint, sub: sub || 'Перетащи каждую карточку к её паре' })
};
const near = (x, n = 3, d = 5) => uniq(n, () => { let v; do v = x + R(-d, d); while (v === x || v < 0); return v; });

